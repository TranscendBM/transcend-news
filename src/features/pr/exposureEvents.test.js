import { describe, it, expect } from 'vitest';

import { detectEvent, MAX_DELAY_DAYS } from './exposureEvents.js';

const ev = (title, day) => detectEvent(title, day);
const keyOf = (title, day) => ev(title, day)?.key ?? null;

describe('detectEvent — 月營收公告', () => {
  // 使用者提供的「同一篇轉發」標題：全部發布於 2026/10/6，都是 9 月營收公告
  const SEPT = [
    '威剛9月營收年增2倍、Q3首破500億！創見前9月增370%創高',
    '記憶體需求續旺！創見9月營收60.4億年月雙增 Q3營收大增291% 將參展智慧能源週 DDR5、企業級SSD搶AI商機',
    '創見 115年9月營收60.35億、年增290.42%',
    '創見9月營收60.35億元年增290.42% 1—9月達485.11億元',
    '創見9月營收60.4億元、年增290% 深化AI與工業應用布局',
    '創見9月營收回溫月增24.8% IPC、網通客戶專案出貨挹注',
    '創見9月營收達60.4億元年增290% AI伺服器記憶體、SSD需求同步升溫',
    '創見9月營收轉雙增/Q3寫次高；續拓AI應用',
    '創見資訊 9 月營收年增 290%，前 9 個月營收年增達到 370%',
    '創見Q3營收160.7億元創次高 深化AI及工控應用',
    '《半導體》創見Q3營收寫次高 前3季成長3.7倍',
  ];

  it('各種寫法（9月、前9月、1—9月、前9個月、Q3、前3季、115年9月）都認成同一期：2026年9月', () => {
    SEPT.forEach(t => expect(keyOf(t, '2026-10-06'), t).toBe('revenue:2026-9'));
    expect(ev(SEPT[0], '2026-10-06').label).toBe('2026年9月營收公告');
    expect(ev(SEPT[0], '2026-10-06').kind).toBe('revenue');
  });

  it('其他月份的寫法：前七月、中文數字、4、5月、4~5月、第一季、首季、上半年、H1', () => {
    expect(keyOf('創見營收／前七月達376億元 已超越歷年最高全年紀錄', '2026-08-06')).toBe('revenue:2026-7');
    expect(keyOf('創見營收／7月52億元年增逾3倍 前七月提前改寫全年紀錄', '2026-08-06')).toBe('revenue:2026-7');
    expect(keyOf('創見高階產品需求強 4、5月營收總和已超越Q1', '2026-06-03')).toBe('revenue:2026-5');
    expect(keyOf('創見5月營收年增近4.7倍！累計4~5月營收已超越首季', '2026-06-03')).toBe('revenue:2026-5');
    expect(keyOf('創見營收／第一季達136億元創新高 一季達成去年全年近八成', '2026-04-08')).toBe('revenue:2026-3');
    expect(keyOf('創見3月及首季合併營收同寫歷史新高', '2026-04-08')).toBe('revenue:2026-3');
    expect(keyOf('創見半年營收逼近去年全年2倍！樂觀看待下半年記憶體需求', '2026-07-06')).toBe('revenue:2026-6');
    expect(keyOf('受惠價格雙漲！威剛與創見上半年營收齊創新高', '2026-07-06')).toBe('revenue:2026-6');
    expect(keyOf('【公告】創見 2026年3月合併營收56.84億元 年增380.57%', '2026-04-08')).toBe('revenue:2026-3');
    expect(keyOf('營收速報 - 創見(2451)7月營收51.95億元年增率高達307.66％', '2026-08-06')).toBe('revenue:2026-7');
  });

  it('期間必須已經結束：標題提到還沒結束的月份／季不採用，取已結束的最近一期', () => {
    // 6/3 發布：Q2 還沒結束（6/30），應該是 5 月營收
    expect(keyOf('創見5月營收衝上62.98億元！第二季前兩月已超越第一季整季', '2026-06-03')).toBe('revenue:2026-5');
    // 7/6 發布：「3Q」還沒到
    expect(keyOf('創見2Q26營收創新高 專案遞延至3Q不減強勁動能', '2026-07-06')).toBe('revenue:2026-6');
  });

  it('跨年：1 月發布的 12 月營收、去年的 Q4', () => {
    expect(keyOf('創見12月營收創高 全年營收破千億', '2027-01-06')).toBe('revenue:2026-12');
    expect(keyOf('創見第4季營收創新高', '2027-01-08')).toBe('revenue:2026-12');
  });

  it('不同月份的營收公告不會同一個事件（即使同一天發布）', () => {
    expect(keyOf('創見7月營收年增3倍', '2026-09-02')).not.toBe(keyOf('創見8月營收年增2倍', '2026-09-02'));
  });

  it('太久以前的期間不採用（超過 75 天）：事後很久才提到某月營收的評論不算公告報導', () => {
    expect(MAX_DELAY_DAYS).toBe(75);
    expect(keyOf('創見去年3月營收回顧', '2026-09-20')).toBeNull();
  });

  it('沒有明確期間時，只有「創見＋營收＋月／季字眼＋月初（12 日前）」才推定為上個月營收', () => {
    const inferred = ev('創見第2季前兩月營收已超越歷史單季營收', '2026-06-03');
    expect(inferred.key).toBe('revenue:2026-5');
    expect(inferred.inferred).toBe(true);
    // 沒有月／季字眼：不推定（例如 N1X 那則）
    expect(ev('黃仁勳發表N1X、AI PC來臨！創見：記憶體再大爆發、營收貢獻可觀', '2026-06-03')).toBeNull();
    // 不是月初：不推定
    expect(ev('創見營收創新高 單月成長亮眼', '2026-06-20')).toBeNull();
    // 沒有提到創見：不推定
    expect(ev('記憶體族群營收創新高 單月成長亮眼', '2026-06-03')).toBeNull();
    // 1 月初推定為去年 12 月
    expect(ev('創見營收創新高 單月成長亮眼', '2027-01-05').key).toBe('revenue:2026-12');
  });

  it('標題沒有營收字眼、或沒有任何期間時不歸類', () => {
    expect(ev('創見推出新品 SSD', '2026-10-06')).toBeNull();
    expect(ev('創見董事長談記憶體缺貨將延續到明年', '2026-10-06')).toBeNull();
    expect(ev('', '2026-10-06')).toBeNull();
    expect(ev('創見9月營收', '')).toBeNull();
    expect(ev(null, '2026-10-06')).toBeNull();
  });
});

describe('detectEvent — 季度財報／獲利', () => {
  const Q2 = [
    'AI太強！創見Q2獲利年增27倍、EPS27.7元 單季賺贏過去每一年',
    '創見第2季賺贏歷年全年水準 上半年每股純益46.63元創新高',
    '【26Q2財報公告】創見(2451) Q2 營收188.1542億元，季增 38.06％、年成長 482.44％',
    '財報：創見115年上半年營益率73.70%，稅後盈餘200億1971萬元，EPS 46.63元',
    '創見2Q26獲利高達119億元 單季表現超越過往全年總和',
    '創見 115年第2季綜合損益表，每股盈餘27.70元',
    '《半導體》H1每股賺46.63元再創高 創見逆攻8%',
  ];

  it('Q2／第2季／上半年／H1／2Q26／26Q2 都認成同一季（2026 年第 2 季）', () => {
    Q2.forEach(t => expect(keyOf(t, '2026-07-23'), t).toBe('earnings:2026-6'));
    expect(ev(Q2[0], '2026-07-23').label).toBe('2026年第2季財報／獲利');
    expect(ev(Q2[0], '2026-07-23').kind).toBe('earnings');
  });

  it('財報公告標題裡雖然有「營收」，仍歸財報（不是月營收）', () => {
    expect(ev('【26Q2財報公告】創見(2451) Q2 營收188.1542億元', '2026-07-23').kind).toBe('earnings');
  });

  it('標題明確寫「N月營收」就是營收公告，即使同時有獲利字眼', () => {
    expect(ev('創見9月營收60.4億元 獲利可期', '2026-10-06').kind).toBe('revenue');
  });

  it('第 1 季財報與第 2 季財報是不同事件', () => {
    expect(keyOf('創見第一季每股獲利18.93元 單季賺贏去年', '2026-05-08')).toBe('earnings:2026-3');
    expect(keyOf('創見Q1獲利季增149% 每股賺18.93元創新高', '2026-05-08')).not.toBe(keyOf(Q2[0], '2026-07-23'));
  });
});

describe('detectEvent — 展覽參展', () => {
  it('同一個展、同一個月的各種寫法合成同一個事件（能源週＝智慧能源週）', () => {
    const a = ev('創見參展能源週，展示三大產品線', '2026-10-06');
    const b = ev('創見參展智慧能源週 聚焦AI視覺、高效運算', '2026-10-06');
    expect(a.key).toBe(b.key);
    expect(a).toMatchObject({ kind: 'expo', key: 'expo:energy-week:2026-10', label: '2026年10月 智慧能源週 參展' });
  });

  it('展覽的別名認成同一個展：Touch Taiwan＝智慧製造展；COMPUTEX 不分大小寫', () => {
    expect(keyOf('創見宣布參展2026 Touch Taiwan，主攻智慧製造應用商機', '2026-04-01'))
      .toBe(keyOf('創見首度亮相2026智慧製造展 聚焦高速儲存解決方案', '2026-04-01'));
    expect(keyOf('創見參展Computex 2026 秀AI嵌入式', '2026-05-19')).toBe('expo:computex:2026-5');
    expect(keyOf('創見進軍2026自動化工業展 秀AI視覺辨識應用', '2026-08-12'))
      .toBe(keyOf('創見資訊參展2026台北國際自動化工業大展', '2026-08-12'));
  });

  it('預告與開展期間跨週也算同一事件（同一個月內）；不同月份是不同事件', () => {
    expect(keyOf('創見前進COMPUTEX 2026 展示AI運算儲存解決方案', '2026-05-26'))
      .toBe(keyOf('創見參展COMPUTEX 2026 秀AI嵌入式', '2026-05-19'));
    expect(keyOf('創見資訊榮獲COMPUTEX 2026永續設計獎金獎', '2026-06-02'))
      .not.toBe(keyOf('創見參展COMPUTEX 2026 秀AI嵌入式', '2026-05-19'));
  });

  it('標題沒有「創見」就不歸類（例如只是剛好提到展覽的別家新聞）', () => {
    expect(ev('笑瘋！科技圈重要精神象徵 乖乖現身COMPUTEX爆紅', '2026-06-03')).toBeNull();
  });

  it('營收／財報標題裡順帶提到「將參展…」仍歸營收公告，不被展覽規則搶走', () => {
    const e = ev('記憶體需求續旺！創見9月營收60.4億年月雙增 Q3營收大增291% 將參展智慧能源週', '2026-10-06');
    expect(e.kind).toBe('revenue');
  });

  it('沒列在展覽名單的展不會被規則認出（交給相似標題處理）', () => {
    expect(ev('創見參加某某新興展覽 展示新品', '2026-09-10')).toBeNull();
  });
});
